/**
 * Утилиты для раскладки клеток Монополии на квадратной сетке 11x11.
 *
 * Используются и в Board.vue (для grid-template-column/row), и в
 * GameView.vue (для расчёта позиции всплывающих подсказок с учётом
 * того, в каком «секторе» доски находится клетка — верх, низ, лево,
 * право).
 *
 * Расположение клеток в Монополии:
 *  - id 0-10:  нижняя строка, справа налево (id 0 в правом нижнем углу)
 *  - id 11-19: левая колонка, снизу вверх
 *  - id 20:    не входит в «рамку» — это «Бесплатная стоянка» в углу
 *  - id 21-30: верхняя строка, слева направо
 *  - id 31-39: правая колонка, сверху вниз
 */

export type BoardSide = "top" | "bottom" | "left" | "right" | "corner";

export interface GridPos {
  /** Строка в сетке 1..11. */
  row: number;
  /** Колонка в сетке 1..11. */
  col: number;
}

/**
 * Возвращает координаты клетки в сетке 11x11 (row/col).
 * Совпадает с `getGridPos` в Board.vue.
 */
export function getCellGridPos(i: number): GridPos {
  if (i <= 10) return { row: 11, col: 11 - i };
  if (i <= 19) return { row: 11 - (i - 10), col: 1 };
  if (i <= 30) return { row: 1, col: i - 19 };
  return { row: i - 29, col: 11 };
}

/**
 * Определяет «сектор» клетки на доске.
 *  - "top"    — верхний ряд (id 21..30) и угловая парковка (id 20)
 *               лежит на границе top/bottom — для неё вернём "top",
 *               т.к. визуально она ближе к верхнему ряду;
 *  - "bottom" — нижний ряд (id 0..10);
 *  - "left"   — левая колонка (id 11..19);
 *  - "right"  — правая колонка (id 31..39).
 *
 * Используется для расчёта позиции всплывающей подсказки `CellTooltip`:
 * для top — тултип «свисает» вниз внутрь доски, для bottom — «торчит»
 * вверх, для left — «торчит» вправо, для right — «торчит» влево.
 */
export function getCellSide(id: number): BoardSide {
  if (id >= 21 && id <= 30) return "top";
  if (id === 20) return "top"; // PARKING — назовём "top", чтобы тултип уходил вниз
  if (id >= 0 && id <= 10) return "bottom";
  if (id >= 11 && id <= 19) return "left";
  return "right";
}
