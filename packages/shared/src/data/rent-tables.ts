/**
 * Справочные таблицы ренты для «специальных» клеток (RAILROAD, UTILITY).
 *
 * ВАЖНО: для обычных PROPERTY-участков таблица ренты хранится прямо
 * в поле `cell.rentTable` (см. `data/board.ts`). Здесь собраны формулы
 * для станций и предприятий, которые НЕ хранятся в доске, потому что
 * рента зависит от количества таких клеток у владельца.
 *
 * Значения ЗАШИТЫ в правилах нашей Монополии (см. GDD §4 «Аренда»).
 * При смене правил — править в одном месте.
 */

/**
 * Рента ж/д станции в зависимости от количества станций у владельца.
 *
 * Индекс = кол-во станций у владельца (0..4). По правилам Монополии
 * рента станции удваивается с каждой дополнительной:
 *   1 станция = 25₽
 *   2 станции = 50₽
 *   3 станции = 100₽
 *   4 станции = 200₽
 *
 * В `BOARD` сейчас у `cell.rent` указана базовая рента за 1 станцию (25).
 */
export const RAILROAD_RENT_BY_COUNT: readonly number[] = [0, 25, 50, 100, 200];

/**
 * Множитель для утилит (предприятий — Электричество/Водопровод).
 *
 * Аренда предприятия = (сумма кубиков) × множитель. По правилам
 * Монополии:
 *   1 предприятие у владельца  →  ×4
 *   2 предприятия (комплект)   →  ×10
 *
 * Индекс = кол-во предприятий у владельца (0..2).
 */
export const UTILITY_MULTIPLIER_BY_COUNT: readonly number[] = [0, 4, 10];

/**
 * Стоимость выкупа из залога = mortgageValue × 1.1 (с округлением
 * вверх). Зеркалит `BuildService.getUnmortgageCost` и
 * `MortgageService.getUnmortgageCost` на сервере.
 */
export const UNMORTGAGE_INTEREST_RATE = 1.1;
